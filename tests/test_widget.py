import pytest

from src.widget import get_date, mask_account_card


@pytest.mark.parametrize(
    "input_str, expected",
    [
        # Тесты для карт (16 цифр)
        ("Счет 1234567890123456", "Счет 1234 56** **** 3456"),
        ("Карта 1234567890123456", "Карта 1234 56** **** 3456"),
        ("Visa 1234567890123456", "Visa 1234 56** **** 3456"),
        ("MasterCard 1234567890123456", "MasterCard 1234 56** **** 3456"),
        # Тесты для счетов (не 16 цифр)
        ("Счет 1234567890", "Счет **7890"),
        ("Счет 12345", "Счет **2345"),
        ("ИнойСчет 12345678901234567890", "ИнойСчет **7890"),
        # Тесты с дополнительными пробелами и разным форматированием
        ("  Счет  1234567890  ", "Счет **7890"),
        ("Карта  1234 5678 9012 3456", "Карта 1234 56** **** 3456"),
        # Граничные случаи (некорректные данные)
        ("Счет безномера", "Счет безномера"),  # Без изменений
        ("Только текст", "Только текст"),  # Без изменений
        ("1234567890123456", "1234 56** **** 3456"),  # Без текста
        ("", ""),  # Пустая строка
        ("Карта 1234abc567890123456", "Карта 1234 56** **** 3456"),  # Извлекает цифры
        ("Карта 1234-5678-9012-3456", "Карта 1234 56** **** 3456"),  # Извлекает цифры
    ],
)
def test_mask_account_card(input_str: str, expected: str) -> None:
    assert mask_account_card(input_str) == expected


@pytest.mark.parametrize(
    "date_time, expected",
    [
        # Стандартные случаи
        ("2023-10-05T12:30:45", "05.10.2023"),
        ("1999-01-31T00:00:00", "31.01.1999"),
        ("2050-12-31T23:59:59", "31.12.2050"),
        # Граничные случаи и нестандартные строки
        ("2023-02-28", "28.02.2023"),  # Нет времени
        ("2023-02-28T", "28.02.2023"),  # Пустое время
        ("2023-02-28T12:30", "28.02.2023"),  # Неполное время
        # Некорректные данные
        ("2023-10-05", "05.10.2023"),  # Нет T вообще
        ("2023-10-05ABC12:30:45", "05.10.2023"),  # Мусор после даты
        ("2023-10-05T12:30:45Extra", "05.10.2023"),  # Мусор после времени
        ("", ""),  # Пустая строка
        ("JustText", "JustText"),  # Нет даты
        ("2023/10/05T12:30:45", "2023/10/05T12:30:45"),  # Неправильный разделитель
        ("2023-13-01T12:30:45", "01.13.2023"),  # Невалидный месяц
        ("2023-02-30T12:30:45", "30.02.2023"),  # Невалидный день
        ("2023-10-05T12:30:45Textra", "05.10.2023"),  # Несколько T
    ],
)
def test_get_date(date_time: str, expected: str) -> None:
    assert get_date(date_time) == expected


def test_get_date_no_date() -> None:
    assert get_date("NoDateHere") == "NoDateHere"
